"""LLM へ送るプロンプト。

早押しクイズの問題文であることを必ず伝える。これを省いて「続きを補完して」
とだけ指示すると、「日本で一番高い山は富士山です」から
「富士山は静岡県と山梨県の県境にあり、標高 3776m です」のような説明文が
返り、問いの形にならず答えを出せない。

プロンプトはプロバイダ間で共通のものを使い、社ごとの最適化はしない。
社ごとに変えると予測精度の比較が公平でなくなるため。

JSON 形式の強制（Structured Outputs / response_format）は使わない。
応答フォーマット違反の観測もこの PoC の目的であり、強制すると違反が
発生しなくなるため。プレーンな指示だけで JSON を要求する。
"""

from __future__ import annotations

# 早押しクイズ特有の注意。パラレル問題（「〜ですが、」で前半を振ってから
# 後半で別を問う形式）が頻出するため、途中までの内容がそのまま答えを
# 指すとは限らないことを明示する。これを書かないと
# 「日本で一番高い山は富士山です」の時点で答えを「富士山」と出しやすく、
# この PoC で観測したい「どこで正しく分岐できるか」が測れない。
_QUIZ_CONTEXT = """\
あなたは早押しクイズの解答者です。入力は日本語の早押しクイズの問題文です。

早押しクイズには次の特徴があります。
- 問題文は必ず問いの形（疑問文）で終わる 1 問の文章です。
- 「AはXですが、BはYでしょう？」のように、前半で一つの話題を振ってから
  後半で別のことを問う形式（パラレル問題）が頻出します。
  そのため、文の前半に出てくる語がそのまま答えになるとは限りません。\
"""

_BUZZ_INSTRUCTION = """\
以下は、読み上げの途中で早押しされたため、途中までしか読まれていない問題文です。
文の途中や単語の途中で切れていることがあります。

この続きを予測して問題文を完成させ、その完成した問題文に対する答えを出してください。

次の JSON だけを出力してください。前後に説明や記号を付けないでください。
{"continuation": "<補完した問題文の全文>", "answer": "<答え>"}

- continuation は続きの部分だけでなく、冒頭から末尾までを含む問題文の全文です。
- continuation は問いの形（疑問文）で終わらせてください。
- answer は補完した問題文に対する答えのみを簡潔に書いてください。\
"""

_TIMEUP_INSTRUCTION = """\
以下は、最後まで読み上げられた問題文です。

この問題文に対する答えを出してください。

次の JSON だけを出力してください。前後に説明や記号を付けないでください。
{"answer": "<答え>"}

- answer は答えのみを簡潔に書いてください。\
"""


def build_prompt(partial_text: str, *, complete: bool) -> str:
    """問題文からプロンプトを組み立てる。

    complete が True なら読み切られているため続きの予測は要らず、答えだけを求める。
    """
    instruction = _TIMEUP_INSTRUCTION if complete else _BUZZ_INSTRUCTION
    return f"{_QUIZ_CONTEXT}\n\n{instruction}\n\n---\n{partial_text}\n---"
